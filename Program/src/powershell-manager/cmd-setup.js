// v0.0.63: setup CMD downloads a pinned agent and starts it; token printed by PLA.
export const PLA_SOURCE='https://raw.githubusercontent.com/xcxc84584-prog/ClusterOpt/main/Program/local-agent/server.mjs';
export const SETUP_FILENAME='ClusterOpt-PLA-Setup-v0.0.63-r1.cmd';
export function createSetupCmd(){
 const lines=[
 '@echo off',
 'setlocal EnableExtensions DisableDelayedExpansion',
 'title ClusterOpt Local Agent v0.0.63 r1',
 'echo ==========================================',
 'echo ClusterOpt PowerShell Local Agent v0.0.63 r1',
 'echo ==========================================',
 'where node.exe >nul 2>nul',
 'if errorlevel 1 goto missing_node',
 'set "AGENT_DIR=%USERPROFILE%\\ClusterOpt-Agent"',
 'set "AGENT_FILE=%AGENT_DIR%\\server.mjs"',
 'if not exist "%AGENT_DIR%" mkdir "%AGENT_DIR%"',
 'if errorlevel 1 goto failed',
 'echo [1/2] Downloading pinned agent...',
'powershell.exe -NoProfile -NonInteractive -Command "try { Invoke-WebRequest -UseBasicParsing -Uri '+PLA_SOURCE+' -OutFile ($env:USERPROFILE + \'\\\\ClusterOpt-Agent\\\\server.mjs\') -ErrorAction Stop } catch { exit 1 }"',
 'if errorlevel 1 goto failed',
 'echo [1/3] Downloading native ConPTY bridge and package metadata...',
 'powershell.exe -NoProfile -NonInteractive -Command "$base=\'https://raw.githubusercontent.com/xcxc84584-prog/ClusterOpt/main/Program/local-agent/\'; $dir=Join-Path $env:USERPROFILE \'ClusterOpt-Agent\'; foreach($file in @(\'native-terminal.mjs\',\'package.json\')){try{Invoke-WebRequest -UseBasicParsing -Uri ($base+$file) -OutFile (Join-Path $dir $file) -ErrorAction Stop}catch{exit 1}}"',
 'if errorlevel 1 goto failed',
 'echo [2/3] Installing native terminal dependencies (requires Node.js build tools on Windows)...',
 'pushd "%AGENT_DIR%"',
 'call npm.cmd install --omit=dev --no-audit --no-fund',
 'if errorlevel 1 (popd & goto failed)',
 'popd',
 'echo [3/3] Checking local port 43881...',
 'powershell.exe -NoProfile -NonInteractive -Command "$c=Get-NetTCPConnection -LocalAddress 127.0.0.1 -LocalPort 43881 -State Listen -ErrorAction SilentlyContinue; if($c){exit 12}else{exit 0}"',
 'if errorlevel 12 goto port_busy',
 'goto launch_agent',
 ':port_busy',
 'echo [WARNING] Port 43881 is in use. Choosing Y will stop its listener even if it is NOT ClusterOpt.',
 'echo This can interrupt another local service. No process identity check is performed.',
 'set "CONFIRM="',
 'set /p "CONFIRM=Force use port 43881? [Y/N]: "',
 'if /I not "%CONFIRM%"=="Y" goto cancel_replace',
 'powershell.exe -NoProfile -NonInteractive -Command "$c=@(Get-NetTCPConnection -LocalPort 43881 -State Listen -ErrorAction SilentlyContinue); if(!$c){exit 0}; $ids=@($c | Select-Object -ExpandProperty OwningProcess -Unique); foreach($pidToStop in $ids){try{Stop-Process -Id $pidToStop -Force -ErrorAction Stop}catch{exit 13}}; Start-Sleep -Milliseconds 500; if(Get-NetTCPConnection -LocalPort 43881 -State Listen -ErrorAction SilentlyContinue){exit 14}"',
 'if errorlevel 1 goto unsafe_replace',
 'goto launch_agent',
 ':unsafe_replace',
 'echo [ERROR] Port 43881 could not be released. No elevated permissions were requested.',
 'pause',
 'exit /b 1',
 ':cancel_replace',
 'echo Cancelled. Existing service was not modified.',
 'pause',
 'exit /b 1',
 ':launch_agent',
 'echo [3/3] Starting detached local agent...',
 'set "AGENT_LOG=%AGENT_DIR%\\agent-stdout.log"',
 'set "AGENT_ERR=%AGENT_DIR%\\agent-stderr.log"',
 'if exist "%AGENT_LOG%" del /q "%AGENT_LOG%"',
 'if exist "%AGENT_ERR%" del /q "%AGENT_ERR%"',
 'powershell.exe -NoProfile -NonInteractive -Command "$ErrorActionPreference=\'Stop\'; $dir=Join-Path $env:USERPROFILE \'ClusterOpt-Agent\'; $file=Join-Path $dir \'server.mjs\'; $out=Join-Path $dir \'agent-stdout.log\'; $err=Join-Path $dir \'agent-stderr.log\'; Start-Process -FilePath (Get-Command node.exe).Source -ArgumentList @(\'\"\'+$file+\'\"\') -WorkingDirectory $dir -WindowStyle Hidden -RedirectStandardOutput $out -RedirectStandardError $err -PassThru | Out-Null"',
 'if errorlevel 1 goto failed',
 'echo Waiting for local agent...',
 'powershell.exe -NoProfile -NonInteractive -Command "$log=Join-Path $env:USERPROFILE \'ClusterOpt-Agent\\agent-stdout.log\'; $ready=$false; for($i=0;$i -lt 60;$i++){Start-Sleep -Milliseconds 250; if(Test-Path $log){$s=Get-Content -Raw $log -ErrorAction SilentlyContinue; if($s -match \'Pairing token \\(do not share\\): ([a-f0-9]{64})\'){Write-Host \'==========================================\'; Write-Host \'PAIRING TOKEN (keep private):\'; Write-Host $Matches[1]; Write-Host \'==========================================\'; $ready=$true; break}}}; if(!$ready){Write-Host \'Agent did not report readiness. Check agent-stderr.log\'; exit 1}"',
 'if errorlevel 1 goto failed',
 'echo.',
 'echo Agent is running independently. You may close this CMD window.',
 'echo Closing this window will NOT stop the local agent.',
 'pause',
 'exit /b 0',
 ':missing_node',
 'echo [ERROR] Node.js 20 or later is required.',
 'pause',
 'exit /b 1',
 ':failed',
 'echo [ERROR] Agent setup failed.',
 'pause',
 'exit /b 1'
 ];
 return lines.join('\r\n')+'\r\n';
}
